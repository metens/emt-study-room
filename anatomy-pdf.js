let anatomyPdfIndex = 0;
function anatomyPdfPractice(index = anatomyPdfIndex) {
  anatomyPdfIndex = index;
  const round = ANATOMY_PDF_ROUNDS[index];
  const position = ([x,y,w,h]) => `left:${x/round.width*100}%;top:${y/round.height*100}%;width:${w/round.width*100}%;height:${h/round.height*100}%`;
  const diagram = `/diagrams/anatomy-pdf-round-${round.asset}.jpg`;
  app.innerHTML = heading('Anatomy & physiology diagrams','Practice labeling the original diagrams from your EMT handout.') + `
    <section class="contentcard">
      <label>Choose a diagram
        <select id="anatomy-pdf-picker">${ANATOMY_PDF_ROUNDS.map(({title},i)=>`<option value="${i}" ${i===index?'selected':''}>${esc(title)}</option>`).join('')}</select>
      </label>
      <h2>${esc(round.title)}</h2>
      <p class="muted">Handout page ${round.page} · ${round.labels.length} labels. Select a number on the diagram or type in the matching blank below. Use the patient’s right and left.</p>
      <div style="overflow:auto">
        <div style="position:relative;min-width:320px;max-width:${Math.min(740,round.width*1.7)}px">
          <img src="${diagram}" width="${round.width}" height="${round.height}" alt="${esc(round.title)} with numbered labels" style="width:100%;height:auto;display:block">
          ${round.masks.map(mask=>`<span aria-hidden="true" style="position:absolute;background:#fff;${position(mask)}"></span>`).join('')}
          ${round.labels.map((label,i)=>`<button type="button" data-anatomy-pdf-label="${i}" aria-label="Go to label ${i+1}" style="position:absolute;padding:0;border:0;border-radius:2px;min-height:0;line-height:1;font-size:clamp(8px,1.4vw,13px);background:#e3efcc;color:#183e35;${position(label)}">${i+1}</button>`).join('')}
        </div>
      </div>
      <form id="anatomy-pdf-form">
        <div style="display:grid;grid-template-columns:repeat(auto-fit,minmax(155px,1fr));gap:10px;margin:1rem 0">
          ${round.labels.map((_,i)=>`<label>Label ${i+1}<input name="label-${i}" type="text" autocomplete="off" spellcheck="false" style="width:100%"><small data-anatomy-pdf-feedback="${i}"></small></label>`).join('')}
        </div>
        <div class="actions">
          <button class="primary" type="submit">Check labels</button>
          <button type="reset">Reset answers</button>
          ${index+1<ANATOMY_PDF_ROUNDS.length?`<button type="button" id="anatomy-pdf-next">Next diagram →</button>`:''}
        </div>
        <p id="anatomy-pdf-score" role="status"></p>
      </form>
      <details><summary>Reveal the original labeled diagram</summary>
        <img src="${diagram}" alt="${esc(round.title)} from the handout with its original labels" style="display:block;width:100%;max-width:${Math.min(740,round.width*1.7)}px">
        <ol>${round.labels.map(label=>`<li>${esc(label[4][0])}</li>`).join('')}</ol>
      </details>
    </section>
    <section class="contentcard"><details><summary>Review the handout’s key terms</summary>
      <p><strong>Anatomy</strong> studies body structure. <strong>Physiology</strong> studies body function.</p>
      <p><strong>Palmar</strong> refers to the palm of the hand. <strong>Plantar</strong> refers to the sole of the foot.</p>
      <p>The midclavicular lines run through the midpoints of the clavicles. The midaxillary line runs down the side of the body through the middle of the armpit.</p>
    </details></section>`;
  const picker = app.querySelector('#anatomy-pdf-picker');
  const form = app.querySelector('#anatomy-pdf-form');
  const score = app.querySelector('#anatomy-pdf-score');
  const feedback = [...form.querySelectorAll('[data-anatomy-pdf-feedback]')];
  picker.addEventListener('change', () => changeAnatomyPdfRound(Number(picker.value)));
  app.querySelector('#anatomy-pdf-next')?.addEventListener('click', () => changeAnatomyPdfRound(index+1));
  app.querySelectorAll('[data-anatomy-pdf-label]').forEach(button => {
    button.addEventListener('click', () => form.elements['label-' + button.dataset.anatomyPdfLabel].focus());
  });
  form.addEventListener('submit', event => {
    event.preventDefault();
    const normalize = value => value.toLowerCase().replace(/[^a-z0-9]/g,'');
    let correct = 0;
    round.labels.forEach((label,i) => {
      const value = normalize(form.elements['label-'+i].value);
      const hit = label[4].some(answer => normalize(answer) === value);
      correct += Number(hit);
      feedback[i].textContent = hit ? 'Correct' : value ? 'Try again' : 'Blank';
    });
    score.textContent = correct + ' of ' + round.labels.length + ' correct.';
  });
  form.addEventListener('reset', () => {
    score.textContent = '';
    feedback.forEach(item => { item.textContent = ''; });
  });
}
function changeAnatomyPdfRound(index) {
  anatomyPdfPractice(index);
  app.querySelector('#anatomy-pdf-picker').focus();
  window.scrollTo({top:0,behavior:'instant'});
}
